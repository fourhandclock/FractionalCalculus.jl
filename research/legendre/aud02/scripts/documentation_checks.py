"""Check the new audit Markdown, local links/fragments, tables and math delimiters."""
import json,re,unicodedata
from pathlib import Path
from urllib.parse import unquote,urlsplit
from execution import REVIEW

def slug(s):
    s=re.sub(r'`|\*|\$', '', s).lower()
    return re.sub(r'[^\w\- ]','',s).replace(' ','-')

def main():
    failures=[];links=0;tables=0;macros=set();math_blocks=0
    for path in sorted(REVIEW.glob('*.md')):
        source=path.read_text();plain=re.sub(r'```[^\n]*\n.*?```','',source,flags=re.S)
        if source.count('```')%2:failures.append([path.name,'unbalanced code fence'])
        if plain.count('$$')%2:failures.append([path.name,'unbalanced display math'])
        math_blocks+=plain.count('$$')//2
        text=re.sub(r'\$\$.*?\$\$','',plain,flags=re.S)
        if text.count('$')%2:failures.append([path.name,'unbalanced inline math'])
        prose=re.sub(r'\$[^$]*\$','',text,flags=re.S)
        prose=re.sub(r'`[^`]*`','',prose)
        if re.search(r'\\[A-Za-z]+',prose):failures.append([path.name,'LaTeX command outside math/code',re.findall(r'\\[A-Za-z]+',prose)[:10]])
        macros.update(re.findall(r'\\([A-Za-z]+)',plain))
        previous=None
        for line in source.splitlines():
            if line.startswith('|'):
                columns=len(re.findall(r'(?<!\\)\|',line))-1
                if previous is not None and columns!=previous:failures.append([path.name,'table columns',line])
                previous=columns;tables+=1
            else:previous=None
        for match in re.finditer(r'(?<!!)\[[^\]]+\]\(([^)\n]+)\)',source):
            target=match.group(1).strip().strip('<>');parsed=urlsplit(target)
            if parsed.scheme or target.startswith('mailto:'):continue
            links+=1;resolved=(path.parent/unquote(parsed.path)).resolve() if parsed.path else path
            # The final check report is generated by this successful check itself.
            self_report=resolved==REVIEW/'evidence/documentation-checks.json'
            if not resolved.exists() and not self_report:
                failures.append([path.name,'missing target',target]);continue
            if parsed.fragment and resolved.suffix=='.md' and resolved.exists():
                headings={slug(m.group(1)) for m in re.finditer(r'^#{1,6}\s+(.+)$',resolved.read_text(),re.M)}
                if unquote(parsed.fragment) not in headings:failures.append([path.name,'missing fragment',target])
    record={'markdown_files':len(list(REVIEW.glob('*.md'))),'relative_links_checked':links,
        'table_lines_checked':tables,'display_math_blocks':math_blocks,'latex_macros':sorted(macros),
        'checks':'local paths/fragments, Markdown table structure, fences, balanced GitHub math delimiters and no stray LaTeX macros',
        'visual_github_render_performed':False,'failures':failures,'passed':not failures}
    output=REVIEW/'evidence/documentation-checks.json'
    assert not output.exists(),'retain earlier attempt before retry'
    output.write_text(json.dumps(record,indent=2)+'\n')
    print(json.dumps(record,indent=2));raise SystemExit(0 if not failures else 1)
if __name__=='__main__':main()
